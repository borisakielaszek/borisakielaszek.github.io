  const exact = new Map(pairs);
  const translate = value => {
    if (!value) return value;
    const exactMatch = exact.get(value.trim());
    if (exactMatch) return value.replace(value.trim(), exactMatch);
    let result = value;
    for (const [fr, en] of replacements) result = result.split(fr).join(en);
    return result;
  };

  const translateNode = node => {
    if (!node || !node.nodeValue || !node.nodeValue.trim()) return;
    const parent = node.parentElement;
    if (!parent || /^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA|CODE)$/.test(parent.tagName)) return;
    const next = translate(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  };

  const translateElement = element => {
    if (!element || element.nodeType !== Node.ELEMENT_NODE) return;
    for (const current of [element, ...element.querySelectorAll('*')]) {
      if (/^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA|CODE)$/.test(current.tagName)) continue;
      for (const attribute of ['aria-label', 'alt', 'title', 'placeholder', 'value']) {
        if (current.hasAttribute(attribute)) {
          const before = current.getAttribute(attribute);
          const after = translate(before);
          if (after !== before) current.setAttribute(attribute, after);
        }
      }
    }
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateNode(node);
  };

